// Build script for the Aliyah of the Day site.
// Run: node build.js
// Reads config.json and every file in data/, then writes:
//   aliyah.js                 – the daily block used on GoDaddy (current week only)
//   index.html                – "today's Aliyah" page
//   <year>/<parashah>/<n>/    – one permanent page per Aliyah (English + Afrikaans)
//   archive/index.html        – list of all Aliyot
