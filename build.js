function langBlock(a, lang) {
  const c = a[lang], t = L[lang];
  let h = `<p class="r">Parashat ${esc(a.parashah)} ${esc(a.year)} · ${t.ord[a.aliyah - 1]} Aliyah · ${esc(a.ref)} · ${fmtDate(a.date, lang)}</p>`;
  h += `<p class="b">${esc(c.blessing)}</p><h1>${esc(c.hook)}</h1><p class="s">${esc(c.summary)}</p>`;
  c.questions.forEach((q, i) => {
    h += `<h3>${i + 1}. ${esc(q.q)} <span>(${esc(q.ref)})</span></h3><p>${esc(q.answer)}</p>`;
    h += `<div class="k">${q.key.map(k => `<p>${esc(k)}</p>`).join('')}</div>`;
    h += `<div class="a"><span class="l">${t.act}</span><b>${esc(q.action)}</b>${q.detail ? `<p>${esc(q.detail)}</p>` : ''}</div>`;
  });
  if (c.deeper) h += `<div class="d"><span class="l">${t.deep}</span><p>${esc(c.deeper)}</p></div>`;
  if (c.closing || c.actionOfDay) h += `<div class="c"><span class="l">${t.aod}</span>${c.closing ? `<b>${esc(c.closing)}</b>` : ''}${c.actionOfDay ? `<p>${esc(c.actionOfDay)}</p>` : ''}</div>`;
  return h;
}
